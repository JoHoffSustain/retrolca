"""Yield losses of generated processes.

The reactant inputs of a generated process are the stoichiometric amounts
divided by a reaction yield. The excess, i.e. the unreacted part of the
reactants, is split into direct emissions and waste:

    m_in     = m_stoich / yield
    excess   = m_stoich * (1 / yield - 1)
    emission = excess * emission_share
    waste    = excess * (1 - emission_share)

The yield and the emission share are global parameters in openLCA, and the
exchange amounts are written as formulas of them, so that they can be varied
in sensitivity analyses. The emissions are mapped to elementary flows by CAS
number (or name and formula); if an emission to air exists, the emission is
split 50/50 between air and water.
"""

import logging
from dataclasses import dataclass

import olca_schema as o
from rdkit import Chem
from rdkit.Chem import rdMolDescriptors

from . import oipc, pubchem
from .naming import NamingService
from .res import unwrap

log = logging.getLogger(__name__)

YIELD_PARAM = "retro_yield"
EMISSION_SHARE_PARAM = "retro_em_share"

_LOSS = f"(1 / {YIELD_PARAM} - 1)"


def _num(v: float) -> str:
    return f"{v:.10g}"


def formula_of(smiles_code: str) -> str | None:
    mol = Chem.MolFromSmiles(smiles_code)  # ty: ignore
    if not mol:
        return None
    return rdMolDescriptors.CalcMolFormula(mol)


@dataclass
class Reactant:
    """A reactant input of a generated process."""

    smiles: str
    flow: o.Ref
    product_flow: o.Flow | None
    stoich_amount: float


@dataclass
class Emission:
    flow: o.Flow
    share: float


class YieldModel:
    def __init__(
        self,
        ctx: oipc.IpcContext,
        yield_: float,
        emission_share: float,
        waste_provider: o.TechFlow | None,
        naming: NamingService,
        flows: list[o.Flow] | None = None,
        pubchem_lookup: bool = True,
    ):
        if not 0 < yield_ <= 1:
            raise ValueError(f"yield must be in (0, 1], got {yield_}")
        if not 0 <= emission_share <= 1:
            raise ValueError(
                f"emission share must be in [0, 1], got {emission_share}"
            )
        self.ctx = ctx
        self.naming = naming
        self.pubchem_lookup = pubchem_lookup
        self.waste_provider = waste_provider
        self.yield_value = self.__global_param(
            YIELD_PARAM,
            yield_,
            "Reaction yield of the processes generated by retrolca. The "
            "reactant inputs are the stoichiometric amounts divided by "
            "this yield.",
        )
        self.emission_share = self.__global_param(
            EMISSION_SHARE_PARAM,
            emission_share,
            "Share of the unreacted reactants (yield excess) that is "
            "emitted directly in the processes generated by retrolca; the "
            "rest goes to waste treatment.",
        )
        self.index = oipc.ElementaryFlowIndex.of(ctx, flows)
        self.created_flows: list[o.Flow] = []
        self.matched: dict[str, str] = {}  # SMILES -> name
        self.__cas_cache: dict[str, list[str]] = {}
        self.__warned_no_waste = False

    def __global_param(self, name: str, value: float, description: str) -> float:
        client = self.ctx.client
        for d in client.get_descriptors(o.Parameter) or []:
            if not d.name or d.name.lower() != name.lower():
                continue
            p = client.get(o.Parameter, d.id)
            if not p or p.parameter_scope != o.ParameterScope.GLOBAL_SCOPE:
                continue
            existing = float(p.value) if p.value is not None else value
            if abs(existing - value) > 1e-12:
                log.warning(
                    "Global parameter %s exists with value %s; it is used "
                    "instead of the given value %s",
                    name,
                    existing,
                    value,
                )
            return existing
        p = o.new_parameter(name, value)
        p.is_input_parameter = True
        p.description = description
        client.put(p)
        log.info("Created global parameter %s = %s", name, value)
        return value

    # --- inputs

    def input_amount(self, stoich_amount: float) -> tuple[float, str]:
        """Returns the input amount and its formula for a reactant."""
        return (
            stoich_amount / self.yield_value,
            f"{_num(stoich_amount)} / {YIELD_PARAM}",
        )

    def loss_factor(self) -> float:
        return 1 / self.yield_value - 1

    # --- outputs

    def add_losses(self, process: o.Process, reactants: list[Reactant]):
        """Adds the waste and emission exchanges of the yield excess."""
        if not reactants or self.yield_value >= 1:
            return
        self.__add_waste(process, reactants)
        for r in reactants:
            self.__add_emissions(process, r)

    def __add_waste(self, process: o.Process, reactants: list[Reactant]):
        total = sum(r.stoich_amount for r in reactants)
        if self.emission_share >= 1 or total <= 0:
            return
        p = self.waste_provider
        if not p or not p.flow or not p.provider:
            if not self.__warned_no_waste:
                log.warning(
                    "No waste process for the yield excess given; the "
                    "waste part of the excess is not modelled"
                )
                self.__warned_no_waste = True
            return
        amount = total * self.loss_factor() * (1 - self.emission_share)
        e = o.new_output(process, unwrap(p.flow), amount, self.ctx.kg)
        e.flow_property = self.ctx.mass.to_ref()
        e.default_provider = p.provider
        e.amount_formula = (
            f"{_num(total)} * {_LOSS} * (1 - {EMISSION_SHARE_PARAM})"
        )
        e.description = "Unreacted reactants (yield excess) to waste treatment"

    def __add_emissions(self, process: o.Process, r: Reactant):
        name = r.flow.name or r.smiles
        if self.emission_share <= 0:
            return
        emissions, _ = self.__emission_flows(r)
        base = r.stoich_amount * self.loss_factor() * self.emission_share
        for em in emissions:
            e = o.new_output(process, em.flow, base * em.share, self.ctx.kg)
            e.flow_property = self.ctx.mass.to_ref()
            e.amount_formula = (
                f"{_num(r.stoich_amount)} * {_LOSS} * "
                f"{EMISSION_SHARE_PARAM} * {_num(em.share)}"
            )
            e.description = f"Unreacted {name} (yield excess), direct emission"

    def __emission_flows(self, r: Reactant) -> tuple[list[Emission], bool]:
        cas = self.__cas_of(r)
        names = self.__names_of(r)
        formula = formula_of(r.smiles)
        args = dict(
            smiles_code=r.smiles, cas_numbers=cas, names=names, formula=formula
        )
        air, air_how = self.index.find_match(oipc.Compartment.AIR, **args)
        water, water_how = self.index.find_match(
            oipc.Compartment.WATER, **args
        )
        result: list[Emission] = []
        if air and water:
            result = [Emission(air, 0.5), Emission(water, 0.5)]
        elif air:
            result = [Emission(air, 1.0)]
        elif water:
            result = [Emission(water, 1.0)]
        if result:
            self.__log_match(r, cas, [(air, air_how), (water, water_how)])
            return result, False
        flow = self.__create_flow(r, cas, formula)
        return [Emission(flow, 1.0)], True

    def __log_match(self, r: Reactant, cas: list[str], matches) -> None:
        if r.smiles in self.matched:
            return
        parts = []
        for flow, how in matches:
            if not flow:
                continue
            comp = oipc.compartment_of(flow)
            parts.append(f"{comp}: '{flow.name}' (by {how})")
        name = r.flow.name or r.smiles
        self.matched[r.smiles] = name
        log.info(
            "Emissions of '%s' [%s, CAS %s] mapped to %s",
            name,
            r.smiles,
            ", ".join(cas) if cas else "-",
            "; ".join(parts),
        )

    def log_summary(self) -> None:
        log.info(
            "Direct emissions: %d substance(s) mapped to existing elementary "
            "flows, %d new elementary flow(s) created",
            len(self.matched),
            len(self.created_flows),
        )
        for f in self.created_flows:
            log.info(
                "  new flow without characterisation factors: '%s' (CAS %s)",
                f.name,
                f.cas or "-",
            )

    def __cas_of(self, r: Reactant) -> list[str]:
        if r.smiles in self.__cas_cache:
            return self.__cas_cache[r.smiles]
        cas: list[str] = []

        def add(values):
            for v in values or []:
                c = oipc.normalize_cas(v)
                if c and c not in cas:
                    cas.append(c)

        if r.product_flow:
            add([r.product_flow.cas])
        if not cas:
            info = self.naming.get_info(r.smiles)
            if info:
                add(info.cas)
        if not cas and self.pubchem_lookup:
            add(pubchem.cas_of_smiles(r.smiles))
        if not cas:
            log.info("No CAS number found for %s", r.smiles)
        else:
            log.info("CAS number(s) of %s: %s", r.smiles, ", ".join(cas))
        self.__cas_cache[r.smiles] = cas
        return cas

    def __names_of(self, r: Reactant) -> list[str]:
        names: list[str] = []
        for n in [r.flow.name, r.product_flow.name if r.product_flow else None]:
            if not n:
                continue
            names.append(n)
            # e.g. "ammonia, anhydrous, liquid" -> "ammonia"
            if "," in n:
                names.append(n.split(",")[0])
        info = self.naming.get_info(r.smiles)
        if info and info.name:
            names.append(info.name)
        return names

    def __create_flow(
        self, r: Reactant, cas: list[str], formula: str | None
    ) -> o.Flow:
        comp = oipc.Compartment.WATER
        name = r.flow.name or r.smiles
        flow = o.new_elementary_flow(name, self.ctx.mass)
        flow.category = oipc.compartment_path(comp)
        flow.cas = cas[0] if cas else None
        flow.formula = formula
        flow.other_properties = {
            "SMILES": r.smiles,
            "Retrosynthesis-Generated": True,
        }
        flow.description = (
            "Elementary flow generated by retrolca for direct emissions of "
            "unreacted reactants. It has no characterisation factors in the "
            "LCIA methods; check it in the LCIA and add factors if needed."
        )
        self.ctx.client.put(flow)
        self.index.put(flow, comp)
        self.created_flows.append(flow)
        log.warning(
            "Created elementary flow '%s' [%s, CAS %s] (emission to water) "
            "without characterisation factors; check it in the LCIA",
            name,
            r.smiles,
            ", ".join(cas) if cas else "-",
        )
        return flow
